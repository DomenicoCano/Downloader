@Composable
fun FaqScreen() {
    // По умолчанию раскрыт первый пункт — выделенный, с главной информацией
    var open by rememberSaveable { mutableIntStateOf(0) }
    val red = MaterialTheme.colorScheme.primary
    Column {
        Text("Вопросы", style = MaterialTheme.typography.headlineSmall, color = red)
        Spacer(Modifier.height(12.dp))
        LazyColumn {
            items(faq.size) { i ->
                val item = faq[i]
                val expanded = open == i
                val toggle = Modifier.clickable { open = if (expanded) -1 else i }
                val box = if (item.highlight) {
                    // Красная полупрозрачная рамка и лёгкая красная заливка
                    Modifier
                        .padding(bottom = 8.dp)
                        .fillMaxWidth()
                        .background(red.copy(alpha = 0.10f), MaterialTheme.shapes.small)
                        .border(2.dp, red.copy(alpha = 0.55f), MaterialTheme.shapes.small)
                        .then(toggle)
                        .padding(12.dp)
                } else {
                    Modifier.fillMaxWidth().then(toggle).padding(vertical = 12.dp)
                }
                Column(box) {
                    Text(
                        (if (expanded) "− " else "+ ") + item.q,
                        style = MaterialTheme.typography.titleMedium,
                        color = if (item.highlight) red else MaterialTheme.colorScheme.onSurface,
                    )
                    if (expanded) {
                        Spacer(Modifier.height(8.dp))
                        Text(item.a, style = MaterialTheme.typography.bodyMedium)
                    }
                }
                if (!item.highlight) HorizontalDivider(color = MaterialTheme.colorScheme.outline.copy(alpha = 0.4f))
            }
        }
    }
}
